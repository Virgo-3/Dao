def test_direct_runtime_does_not_import_optional_langgraph(tmp_path, monkeypatch):
    original_import = builtins.__import__

    def without_langgraph(name, *args, **kwargs):
        if name.startswith("langgraph"):
            raise ModuleNotFoundError("LangGraph intentionally unavailable")
        return original_import(name, *args, **kwargs)

    monkeypatch.setattr(builtins, "__import__", without_langgraph)
    with Store(tmp_path / "direct.sqlite3") as store:
        agent = Agent(store)
        result = chat_with_runtime(agent, "/state")
        assert result["text"] == "{}"
        before = store.head(), store.events()
        with pytest.raises(RuntimeError, match=r"dao-agent\[langgraph\]"):
            chat_with_runtime(agent, "/help", runtime="langgraph")
        assert (store.head(), store.events()) == before


