def test_runtime_stable_run_id_replays_when_expected_head_is_omitted(tmp_path):
    pytest.importorskip("langgraph.checkpoint.sqlite")

    class Provider:
        reservation_usd = ".1"
        calls = 0

        def respond(self, messages, tools):
            self.calls += 1
            return Reply("hello", 10, 3, ".02", "test")

    provider = Provider()
    path = tmp_path / "runtime.sqlite3"
    checkpoints = tmp_path / "checkpoints.sqlite3"
    with Store(path) as store:
        agent = Agent(store, provider)
        first = chat_with_runtime(agent, "hello", runtime="langgraph",
                                  checkpoint_db=checkpoints, run_id="stable-turn")
        before = store.head(), store.events(), agent.ledger.summary()
        second = chat_with_runtime(agent, "hello", runtime="langgraph",
                                   checkpoint_db=checkpoints, run_id="stable-turn")
        assert second == first
        assert provider.calls == 1
        assert (store.head(), store.events(), agent.ledger.summary()) == before
        with pytest.raises(ConflictError):
            chat_with_runtime(agent, "changed", runtime="langgraph",
                              checkpoint_db=checkpoints, run_id="stable-turn")
        assert provider.calls == 1
    with Store(path) as store:
        reopened = Agent(store, provider)
        assert chat_with_runtime(reopened, "hello", runtime="langgraph",
                                 checkpoint_db=checkpoints, run_id="stable-turn") == first
        assert reopened.ledger.summary()["usage_count"] == 1


